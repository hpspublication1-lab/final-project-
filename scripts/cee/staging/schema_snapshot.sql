-- READ-ONLY. Produces a schema-only SQL script for the `public` schema (plus the
-- storage bucket list and the policies on storage.objects), built entirely from
-- the system catalog. No table rows are read, so no student data can leave.
--
--   psql "$PROD_DB_URL" -At -f scripts/cee/staging/schema_snapshot.sql > prod_schema.sql
--   (or run the same query through the Supabase connector's read-only SQL)
--
-- Then apply prod_schema.sql to an EMPTY staging project. It recreates:
-- extensions, enum types, domains, sequences, functions, tables (columns,
-- defaults, identity, generated), constraints (keys, checks, foreign keys),
-- indexes, views, triggers (incl. public functions triggered from auth.users),
-- RLS settings, policies and grants for anon / authenticated / service_role.
-- Function bodies are not checked at creation, so their order doesn't matter.

SET search_path TO pg_catalog;

WITH
pub AS (SELECT oid FROM pg_namespace WHERE nspname = 'public'),
ext_objs AS (SELECT objid FROM pg_depend WHERE deptype = 'e'),
rels AS (
  SELECT c.oid, c.relname, c.relkind, c.relrowsecurity, c.relforcerowsecurity, c.relacl,
         quote_ident('public') || '.' || quote_ident(c.relname) AS qname
  FROM pg_class c
  WHERE c.relnamespace = (SELECT oid FROM pub) AND NOT c.relispartition
    AND c.oid NOT IN (SELECT objid FROM ext_objs)
),
ddl(ord, sub, stmt) AS (
  SELECT 0, '', 'SET check_function_bodies = off;'
  UNION ALL SELECT 0, '1', 'SET client_min_messages = warning;'

  -- Extensions
  UNION ALL
  SELECT 1, e.extname, format('CREATE EXTENSION IF NOT EXISTS %I WITH SCHEMA %I;', e.extname, n.nspname)
  FROM pg_extension e JOIN pg_namespace n ON n.oid = e.extnamespace
  WHERE e.extname <> 'plpgsql'

  -- Enum types
  UNION ALL
  SELECT 2, t.typname, format('CREATE TYPE public.%I AS ENUM (%s);', t.typname,
         string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder))
  FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid
  WHERE t.typnamespace = (SELECT oid FROM pub) AND t.oid NOT IN (SELECT objid FROM ext_objs)
  GROUP BY t.typname

  -- Domains
  UNION ALL
  SELECT 3, t.typname, format('CREATE DOMAIN public.%I AS %s%s%s%s;', t.typname,
         format_type(t.typbasetype, t.typtypmod),
         CASE WHEN t.typnotnull THEN ' NOT NULL' ELSE '' END,
         coalesce(' DEFAULT ' || t.typdefault, ''),
         coalesce((SELECT string_agg(' CONSTRAINT ' || quote_ident(c.conname) || ' ' || pg_get_constraintdef(c.oid), '' ORDER BY c.conname)
                   FROM pg_constraint c WHERE c.contypid = t.oid), ''))
  FROM pg_type t
  WHERE t.typtype = 'd' AND t.typnamespace = (SELECT oid FROM pub) AND t.oid NOT IN (SELECT objid FROM ext_objs)

  -- Sequences (identity sequences come with their columns)
  UNION ALL
  SELECT 4, r.relname, format('CREATE SEQUENCE IF NOT EXISTS %s;', r.qname)
  FROM rels r
  WHERE r.relkind = 'S' AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = r.oid AND d.deptype = 'i')

  -- Functions and procedures
  UNION ALL
  SELECT 5, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')', pg_get_functiondef(p.oid) || ';'
  FROM pg_proc p
  WHERE p.pronamespace = (SELECT oid FROM pub) AND p.prokind IN ('f', 'p') AND p.oid NOT IN (SELECT objid FROM ext_objs)

  -- Tables
  UNION ALL
  SELECT 6, r.relname, format('CREATE TABLE %s (%s)%s;', r.qname,
    coalesce((
      SELECT string_agg(
        quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
        || CASE WHEN a.attcollation <> 0 AND a.attcollation <> (SELECT oid FROM pg_collation WHERE collname = 'default')
                THEN ' COLLATE ' || (SELECT quote_ident(collname) FROM pg_collation WHERE oid = a.attcollation) ELSE '' END
        || CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY' WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END
        || CASE WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED'
                WHEN ad.adbin IS NOT NULL AND a.attidentity = '' THEN ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid) ELSE '' END
        || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
        ', ' ORDER BY a.attnum)
      FROM pg_attribute a LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
      WHERE a.attrelid = r.oid AND a.attnum > 0 AND NOT a.attisdropped), ''),
    CASE WHEN r.relkind = 'p' THEN ' PARTITION BY ' || pg_get_partkeydef(r.oid) ELSE '' END)
  FROM rels r WHERE r.relkind IN ('r', 'p')

  -- Constraints: keys, uniques, checks, exclusions first; foreign keys later
  UNION ALL
  SELECT CASE WHEN c.contype = 'f' THEN 8 ELSE 7 END, r.relname || '.' || c.conname,
         format('ALTER TABLE ONLY %s ADD CONSTRAINT %I %s;', r.qname, c.conname, pg_get_constraintdef(c.oid))
  FROM pg_constraint c JOIN rels r ON r.oid = c.conrelid
  WHERE c.contype IN ('p', 'u', 'c', 'x', 'f') AND r.relkind IN ('r', 'p') AND c.conislocal

  -- Indexes that don't back a constraint
  UNION ALL
  SELECT 9, r.relname || '.' || ic.relname, pg_get_indexdef(i.indexrelid) || ';'
  FROM pg_index i JOIN rels r ON r.oid = i.indrelid JOIN pg_class ic ON ic.oid = i.indexrelid
  WHERE NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = i.indexrelid)

  -- Views and materialized views (creation order approximates dependencies)
  UNION ALL
  SELECT 10, lpad(r.oid::text, 12, '0'),
         CASE WHEN r.relkind = 'v' THEN format('CREATE OR REPLACE VIEW %s AS %s', r.qname, pg_get_viewdef(r.oid))
              ELSE format('CREATE MATERIALIZED VIEW %s AS %s WITH NO DATA;', r.qname, rtrim(pg_get_viewdef(r.oid), ';')) END
  FROM rels r WHERE r.relkind IN ('v', 'm')

  -- Triggers on public tables, and on any table where the trigger calls a public function (e.g. auth.users signup)
  UNION ALL
  SELECT 11, t.tgname, pg_get_triggerdef(t.oid) || ';'
  FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_proc p ON p.oid = t.tgfoid
  WHERE NOT t.tgisinternal
    AND (c.relnamespace = (SELECT oid FROM pub) OR p.pronamespace = (SELECT oid FROM pub))
    AND t.oid NOT IN (SELECT objid FROM ext_objs)

  -- Row-level security
  UNION ALL
  SELECT 12, r.relname, format('ALTER TABLE %s ENABLE ROW LEVEL SECURITY;', r.qname) FROM rels r WHERE r.relrowsecurity
  UNION ALL
  SELECT 12, r.relname || '~', format('ALTER TABLE %s FORCE ROW LEVEL SECURITY;', r.qname) FROM rels r WHERE r.relforcerowsecurity

  -- Policies on public tables and on storage.objects
  UNION ALL
  SELECT 13, n.nspname || '.' || c.relname || '.' || pol.polname,
         format('CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;', pol.polname, n.nspname, c.relname,
                CASE WHEN pol.polpermissive THEN 'PERMISSIVE' ELSE 'RESTRICTIVE' END,
                CASE pol.polcmd WHEN 'r' THEN 'SELECT' WHEN 'a' THEN 'INSERT' WHEN 'w' THEN 'UPDATE' WHEN 'd' THEN 'DELETE' ELSE 'ALL' END,
                CASE WHEN pol.polroles = '{0}' THEN 'PUBLIC'
                     ELSE (SELECT string_agg(quote_ident(rolname), ', ' ORDER BY rolname) FROM pg_roles WHERE oid = ANY (pol.polroles)) END,
                coalesce(' USING (' || pg_get_expr(pol.polqual, pol.polrelid) || ')', ''),
                coalesce(' WITH CHECK (' || pg_get_expr(pol.polwithcheck, pol.polrelid) || ')', ''))
  FROM pg_policy pol JOIN pg_class c ON c.oid = pol.polrelid JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' OR (n.nspname = 'storage' AND c.relname = 'objects')

  -- Table grants for the Supabase API roles: reset, then grant exactly what production has
  UNION ALL
  SELECT 14, r.relname || '.0', format('REVOKE ALL ON %s FROM %s;', r.qname,
         (SELECT string_agg(quote_ident(rolname), ', ' ORDER BY rolname) FROM pg_roles WHERE rolname IN ('anon', 'authenticated', 'service_role')))
  FROM rels r WHERE r.relkind IN ('r', 'p', 'v', 'm', 'S')
    AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname IN ('anon', 'authenticated', 'service_role'))
  UNION ALL
  SELECT 14, r.relname || '.1.' || g.grantee::text, format('GRANT %s ON %s TO %s;', string_agg(DISTINCT g.privilege_type, ', '), r.qname, quote_ident(ro.rolname))
  FROM rels r CROSS JOIN LATERAL aclexplode(r.relacl) g JOIN pg_roles ro ON ro.oid = g.grantee
  WHERE r.relacl IS NOT NULL AND ro.rolname IN ('anon', 'authenticated', 'service_role')
  GROUP BY r.relname, r.qname, g.grantee, ro.rolname

  -- Function EXECUTE grants (functions default to PUBLIC; reproduce revokes too)
  UNION ALL
  SELECT 15, p.proname || pg_get_function_identity_arguments(p.oid) || '.0',
         format('REVOKE ALL ON FUNCTION public.%I(%s) FROM PUBLIC;', p.proname, pg_get_function_identity_arguments(p.oid))
  FROM pg_proc p
  WHERE p.pronamespace = (SELECT oid FROM pub) AND p.prokind IN ('f', 'p') AND p.proacl IS NOT NULL AND p.oid NOT IN (SELECT objid FROM ext_objs)
  UNION ALL
  SELECT 15, p.proname || pg_get_function_identity_arguments(p.oid) || '.1.' || g.grantee::text,
         format('GRANT EXECUTE ON FUNCTION public.%I(%s) TO %s;', p.proname, pg_get_function_identity_arguments(p.oid),
                CASE WHEN g.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(ro.rolname) END)
  FROM pg_proc p CROSS JOIN LATERAL aclexplode(p.proacl) g LEFT JOIN pg_roles ro ON ro.oid = g.grantee
  WHERE p.pronamespace = (SELECT oid FROM pub) AND p.prokind IN ('f', 'p') AND p.oid NOT IN (SELECT objid FROM ext_objs)
    AND g.privilege_type = 'EXECUTE' AND (g.grantee = 0 OR ro.rolname IN ('anon', 'authenticated', 'service_role'))
)
SELECT stmt FROM ddl ORDER BY ord, sub;

-- Storage buckets (names and settings only; never objects). Separate query so a
-- database without the storage schema still produces the script above.
SELECT CASE WHEN to_regclass('storage.buckets') IS NULL THEN '-- no storage schema' ELSE
  coalesce(replace(replace(replace(replace(replace((xpath('/row/s/text()', query_to_xml($q$
    SELECT string_agg(format('INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (%L, %L, %L, %s, %L) ON CONFLICT (id) DO NOTHING;',
                             id, name, public, coalesce(file_size_limit::text, 'NULL'), allowed_mime_types), E'\n' ORDER BY id) AS s
    FROM storage.buckets $q$, false, true, '')))[1]::text,
    '&lt;', '<'), '&gt;', '>'), '&quot;', '"'), '&apos;', ''''), '&amp;', '&'), '-- no storage buckets') END;
